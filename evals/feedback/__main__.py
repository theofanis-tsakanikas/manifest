"""Claim 1 as a loop: what review evidence does to a threshold.

`evals/calibration/` derives every threshold once, from the committed recording, and thirty-two
of thirty-six fields come out `always-review` — **evidence-limited**, not quality-limited. The
reader is not wrong; there is not enough labelled data to prove it right at the budgets those
fields declare.

This harness answers the question that follows: *how much review would it take?* — and then shows
what happens when that review arrives.

**Where the review evidence comes from here, and what that does and does not prove.**

The decisions are constructed from the corpus's own ground truth: a reviewer shown a queued item
approves when the reader was right and corrects when it was wrong. That makes this harness a
demonstration of the **mechanism** — that corrections enter the derivation, that N grows, that a
field can leave always-review, and that the budget never moves — and not a measurement of what
real reviewers would produce. It is labelled that way here and in the README, because a
"simulated reviewer" quietly presented as evidence about people would be the worst thing in this
repository.

**The property under test is the one that keeps it safe.** A correction changes N. It never
changes an error budget. `gate-proof` plants the arrow from corrections to budget and requires
this harness to refuse it.

**And rubber stamps do not count.** A reviewer who approves everything emits `CORRECT` at
whatever confidence the model produced; the observed error rate falls, the bound tightens, and
the threshold drops on evidence nobody generated by looking. The harness runs a rubber stamp
through the harvest on purpose and requires the observations to be excluded.
"""

from __future__ import annotations

from decimal import Decimal

from evals.harness import by_field, field_contract, score_all
from manifest.core.calibration import Outcome
from manifest.core.feedback import ReviewerIntegrity, harvest, movement
from manifest.core.review import Decision, Record

#: The policy the harvest filters against. Read from the review contract rather than chosen
#: here — see `contracts/review/`. Restated as constants only because this harness has no other
#: reason to load the whole contract set.
MAXIMUM_AGREEMENT_RATE = 0.98
MINIMUM_SECONDS = Decimal("8")

#: How many queued items a careful reviewer gets through, per field, in this scenario. A
#: parameter of the demonstration, not a measurement of anybody's day.
REVIEWED_PER_FIELD = 900


def _reviewer_decisions(entries: list) -> list[tuple[Record, float]]:
    """What a reviewer who actually looks would record, given ground truth.

    Approve when the reader was right, correct when it was wrong. Nothing subtler: modelling
    reviewer error would be inventing a second distribution on top of the one this corpus
    already is, and neither would be a measurement.
    """
    decisions: list[tuple[Record, float]] = []
    for index, entry in enumerate(entries[:REVIEWED_PER_FIELD]):
        if entry.outcome is Outcome.MISSING:
            continue
        right = entry.outcome is Outcome.CORRECT
        decisions.append(
            (
                Record(
                    document=f"{entry.shipment}/{entry.document}",
                    field=entry.field,
                    reviewer="careful",
                    decision=Decision.APPROVED if right else Decision.CORRECTED,
                    value=entry.truth,
                    # Varied a little so the median is not a single value; every one is above
                    # the declared floor, because this reviewer is looking.
                    seconds_on_task=Decimal(20 + (index % 25)),
                    agreed_with_model=right,
                ),
                entry.extracted.confidence if entry.extracted.confidence is not None else 0.0,
            )
        )
    return decisions


def main() -> int:
    scored = by_field(score_all())
    problems: list[str] = []

    print("claim 1, as a loop — what review evidence does to a threshold\n")
    print(
        "  The decisions here are constructed from ground truth: a reviewer who approves when\n"
        "  the reader was right and corrects when it was wrong. This is a demonstration of the\n"
        "  MECHANISM, not a measurement of what real reviewers produce. Said plainly because a\n"
        "  simulated reviewer presented as evidence about people would be the worst thing here.\n"
    )

    moved: list = []
    for field, entries in sorted(scored.items()):
        contract = field_contract(field)
        budget = contract.error_budget
        if budget is None:
            # Declared always-review in the contract itself. No amount of evidence changes that,
            # and pretending otherwise here would be the harness overruling a declaration.
            continue

        baseline = [entry.observation for entry in entries]
        decisions = _reviewer_decisions(entries)
        gathered = harvest(
            field=field,
            decisions=decisions,
            integrity={"careful": ReviewerIntegrity("careful", 500, 460, Decimal("28"))},
            maximum_agreement_rate=MAXIMUM_AGREEMENT_RATE,
            minimum_seconds=MINIMUM_SECONDS,
        )
        change = movement(
            field=field, error_budget=budget, before=baseline, added=gathered.observations
        )

        # The safety property, checked per field rather than once: the budget that came out is
        # the budget that went in.
        if change.error_budget != budget:
            problems.append(
                f"{field}: the error budget changed during derivation ({budget} -> "
                f"{change.error_budget}). Corrections move N and nothing else; a budget that "
                f"moves with review volume has inverted the derivation, which is ADR-0001's "
                f"forbidden move wearing a feedback loop"
            )

        if (
            change.left_always_review
            or change.returned_to_always_review
            or change.before != change.after
        ):
            moved.append((change, gathered))

    if moved:
        print("  fields whose threshold moved when review evidence was added:\n")
        for change, gathered in moved:
            marker = "  LEFT always-review" if change.left_always_review else ""
            print(f"    {change.describe()}{marker}")
            print(f"      {gathered.summary()}")
    else:
        print("  no field's threshold moved at this review volume.")
        print(
            f"      At {REVIEWED_PER_FIELD} reviewed items per field this corpus does not\n"
            f"      supply enough evidence to change any derivation. That is a finding, not a\n"
            f"      failure: `evals/calibration/` prints, per field, how many observations the\n"
            f"      budget would need, and several need thousands."
        )

    # The poisoning path, run on purpose.
    print("\n  the rubber stamp, run deliberately:\n")
    stamped = [
        (
            Record(
                document=f"d{index}",
                field="gross_weight",
                reviewer="stamp",
                decision=Decision.APPROVED,
                value="whatever",
                seconds_on_task=Decimal("30"),
                agreed_with_model=True,
            ),
            0.99,
        )
        for index in range(500)
    ]
    poisoned = harvest(
        field="gross_weight",
        decisions=stamped,
        integrity={"stamp": ReviewerIntegrity("stamp", 500, 500, Decimal("30"))},
        maximum_agreement_rate=MAXIMUM_AGREEMENT_RATE,
        minimum_seconds=MINIMUM_SECONDS,
    )
    print(f"    {poisoned.summary()}")
    if poisoned.total != 0:
        problems.append(
            f"a reviewer with a 100% agreement rate contributed {poisoned.total} observation(s). "
            f"Every one is a CORRECT at whatever confidence the model emitted, so the observed "
            f"error rate falls and the threshold drops on evidence nobody generated by looking"
        )
    else:
        print("      all 500 excluded — a 100% agreement rate is not a control, it is a login")

    # And the reviewer who did not look long enough.
    hurried = harvest(
        field="gross_weight",
        decisions=[
            (
                Record(
                    document=f"h{index}",
                    field="gross_weight",
                    reviewer="hurried",
                    decision=Decision.APPROVED,
                    value="v",
                    seconds_on_task=Decimal("2"),
                    agreed_with_model=True,
                ),
                0.99,
            )
            for index in range(100)
        ],
        integrity={"hurried": ReviewerIntegrity("hurried", 100, 60, Decimal("2"))},
        maximum_agreement_rate=MAXIMUM_AGREEMENT_RATE,
        minimum_seconds=MINIMUM_SECONDS,
    )
    print(f"\n    {hurried.summary()}")
    if hurried.total != 0:
        problems.append(
            f"a reviewer averaging two seconds per decision contributed {hurried.total} "
            f"observation(s). Time on task is the only signal that separates a decision from a "
            f"keystroke"
        )

    if problems:
        print("\nclaim 1 (loop): FAILED\n")
        for problem in problems:
            print(f"  {problem}")
        return 1

    print(
        "\nclaim 1 (loop): corrections enter the derivation, N grows, and the error budget is "
        "\n  untouched. Rubber-stamped and hurried decisions are excluded and counted."
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
